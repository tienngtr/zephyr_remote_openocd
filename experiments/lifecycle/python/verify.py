"""Run actual asyncio histories and three deliberately weakened implementations."""

from __future__ import annotations

import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path


def main() -> None:
    root = Path(__file__).resolve().parent
    repository = root.parents[2]
    scratch = repository / '.scratch/agents/architecture-python/verification'
    scratch.mkdir(parents=True, exist_ok=True)
    command = [sys.executable, '-m', 'pytest', '-q', '-W', 'error']
    result = subprocess.run(
        [*command, str(root / 'test_session.py')],
        cwd=repository,
        capture_output=True,
        text=True,
        check=False,
    )
    log = result.stdout + result.stderr
    (scratch / 'positive.log').write_text(log)
    if result.returncode:
        raise RuntimeError(f'prototype failed: {scratch / "positive.log"}')
    count = re.search(r'(\d+) passed', log)
    assert count is not None
    source = (root / 'session.py').read_text()
    variants = (
        (
            'no_barrier_ack',
            '            if not self.barrier.acknowledged.is_set():\n'
            '                return  # the coordinator keeps draining instead of awaiting ack\n',
            '',
            'test_withheld_stop_blocks_ready_and_barrier_keeps_draining',
        ),
        (
            'generation_only',
            '                or self.phase != Phase.STARTING\n'
            '                or self.outcome.reason is not None\n',
            '',
            'test_queued_same_generation_spawn_is_revoked[True]',
        ),
        (
            'cancellation_settles',
            '            attempt.worker.cancel()\n        self.wake.set()\n',
            '            attempt.worker.cancel()\n            attempt.producer_settled = True\n'
            '            attempt.stage = Stage.SETTLED\n        self.wake.set()\n',
            'test_cancelled_wait_does_not_settle_late_producer_or_allow_retry[Strategy.ATOMIC]',
        ),
    )
    rows = []
    for name, before, after, node in variants:
        if source.count(before) != 1:
            raise RuntimeError(f'{name}: mutation no longer matches exactly one boundary')
        work = scratch / ('mutant_' + name)
        work.mkdir(exist_ok=True)
        for original in root.glob('*.py'):
            shutil.copyfile(original, work / original.name)
        (work / 'session.py').write_text(source.replace(before, after))
        result = subprocess.run(
            [*command, str(work / 'test_session.py') + '::' + node],
            cwd=repository,
            capture_output=True,
            text=True,
            check=False,
        )
        log = result.stdout + result.stderr
        (scratch / (name + '.log')).write_text(log)
        if result.returncode != 1 or 'AssertionError' not in log or 'TimeoutError' in log:
            raise RuntimeError(f'{name}: expected a semantic assertion; see {scratch}')
        rows.append(f'| {name} | `{node}` | Expected semantic assertion failure |')
    hashes = [
        f'| {path.name} | `{hashlib.sha256(path.read_bytes()).hexdigest()}` |'
        for path in sorted(root.glob('*.py'))
    ]
    (root / 'CHECKED.md').write_text(
        '\n'.join(
            (
                '# Checked Python results',
                '',
                f'Generated by `verify.py`. {count[1]} deterministic prototype cases passed '
                'with warnings treated as errors.',
                'The negative runs changed only scratch copies. Each failed at a semantic '
                'assertion, without waiting for the deadlock safety timeout.',
                '',
                '| Weakened variant | Test | Actual checked result |',
                '| --- | --- | --- |',
                *rows,
                '',
                '| Source | SHA-256 |',
                '| --- | --- |',
                *hashes,
                '',
                'These are concrete scheduled histories, not exhaustive state exploration '
                'or a production refinement proof. See [REPORT.md](REPORT.md).',
                '',
            )
        )
    )
    print(f'{count[1]} positive histories and three expected negative results verified.')


if __name__ == '__main__':
    main()
